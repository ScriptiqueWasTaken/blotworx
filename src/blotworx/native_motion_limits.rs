//! EM1 hkUFloat8 lookup, DOL 0x8065da58. Exact decoded limit bits.
//! DOL SHA256: 994779fa2e276983efdb50f02c406568f285a82558cb5d54bbdf74651a98a920.

pub fn decode(encoded: u8) -> f32 {
    f32::from_bits(VALUES[encoded as usize])
}

/// DOL 801661e0: signed comparison of positive float bit patterns, followed
/// by a ceiling lookup. Values below entry 1 become zero; overflow saturates
/// at entry 255. This is not a nearest-value quantizer.
pub fn encode(value: f32) -> anyhow::Result<u8> {
    anyhow::ensure!(value.is_finite(), "Nonfinite motion limit");
    let bits = value.to_bits() as i32;
    if bits < (VALUES[1] as i32) {
        return Ok(0);
    }
    Ok(VALUES
        .partition_point(|&entry| (entry as i32) < bits)
        .min(255) as u8)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn original_limit_encoding_uses_ceiling_and_end_saturation() {
        for i in 0..256 {
            assert_eq!(encode(decode(i as u8)).unwrap(), i as u8);
            if i >= 1 {
                assert_eq!(
                    encode(f32::from_bits(VALUES[i] + 1)).unwrap(),
                    (i + 1).min(255) as u8
                );
                assert_eq!(
                    encode(f32::from_bits(VALUES[i] - 1)).unwrap(),
                    if i == 1 { 0 } else { i as u8 }
                );
            }
        }
        assert_eq!(encode(-100.).unwrap(), 0);
        assert_eq!(encode(-0.).unwrap(), 0);
        assert_eq!(encode(f32::MAX).unwrap(), 255);
        assert!(encode(f32::NAN).is_err());
        assert!(encode(f32::INFINITY).is_err());
    }
}

