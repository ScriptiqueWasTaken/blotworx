-- Run from GV_ZoneC_Start. Use the original broken plant's two knots.
Wait(1)
local plant = assert(GetEntity("gv_zonec.GV_BrokenPlant_Inert 01"))
local start = assert(GetEntity("gv_zonec.SplineKnot_PlantKnot01"))
local finish = assert(GetEntity("gv_zonec.SplineKnot_PlantKnot02"))
assert(SplineFollower_ClearStopPosition(nil) == false)
assert(SplineFollower_ClearStopPosition(start) == false)
assert(SplineFollower_ClearStopPosition(plant) == true)
SplineFollower_TeleportToKnot(plant, start)
SetSplineFollowerInitialSpeed(plant, 8)
assert(SplineFollower_StopAtPosition(plant, start, finish, 0.25))
Wait(0.8)

local distance = GetDistanceBetweenEntities(start, finish)
assert(math.abs(GetDistanceBetweenEntities(plant, start) - distance * 0.25) < 0.05)
assert(SplineFollower_ClearStopPosition(plant))
Wait(0.3)
assert(math.abs(GetDistanceBetweenEntities(plant, start) - distance * 0.25) < 0.05)
SetSplineFollowerInitialSpeed(plant, 8)
Wait(1.5)
-- The final knot's OnPass destroys its activator.
assert(not IsValidHandle(plant), "The plant did not reach its cleanup knot")
Print("ZONE_C_SPLINE_STOP_RELEASE_PASSED")

local chest = assert(GetEntity("gv_zonec.GV_ZoneC_BackRoomTreasure"))
local low = assert(GetEntity("gv_zonec.SplineKnot 09"))
local high = assert(GetEntity("gv_zonec.SplineKnot 10"))
SplineFollower_TeleportToKnot(chest, low)
SetSplineFollowerInitialSpeed(chest, 8)
assert(SplineFollower_StopAtPosition(chest, low, high, 0))
Wait(0.1)
local parked = GetDistanceBetweenEntities(chest, high)
GV_ZoneC_MaintenanceRoomChest()
Wait(0.9)
assert(GetDistanceBetweenEntities(chest, high) < parked - 0.3)
Print("ZONE_C_MAINTENANCE_CHEST_RESUMED")
